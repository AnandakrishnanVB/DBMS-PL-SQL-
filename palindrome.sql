SET SERVEROUTPUT ON;
DECLARE
STR VARCHAR(20) := '&STR';
REV VARCHAR(20) := '';
BEGIN
FOR I IN REVERSE 1..LENGTH(STR) LOOP
    REV := REV || SUBSTR(STR,I,1);
END LOOP;
IF STR = REV THEN
DBMS_OUTPUT.PUT_LINE('String is palindrome.');
ELSE
DBMS_OUTPUT.PUT_LINE('String is not palindrome.');
END IF;
END;
/