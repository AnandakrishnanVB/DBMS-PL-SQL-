SET SERVEROUTPUT ON
DECLARE
TYPE NAMEARRAY IS VARRAY(6) OF VARCHAR(10);
TYPE GRADEARRAY IS VARRAY(7) OF INTEGER;
NAME NAMEARRAY;
MARK GRADEARRAY;
TOTAL INTEGER;
I NUMBER;
BEGIN
NAME := NAMEARRAY('HAII','ABUU','ANU','SIJU','ALU','TUBU');
MARK := GRADEARRAY(100,53,25,22,88,98);
TOTAL := NAME.COUNT;
DBMS_OUTPUT.PUT_LINE('Student details');
FOR I IN 1..TOTAL LOOP
DBMS_OUTPUT.PUT_LINE(NAME(I) || ' ' || MARK(I) || ' ');
END LOOP;
END;
/